/**
 * Lesson 1's open-air bar magnet field, precomputed.
 *
 * The predict stage used hand-drawn bezier loops that did not match a real
 * dipole. These are iso-Az field lines from an actual solve of the same fixture
 * the lesson goes on to run (one magnet, no steel, centred, 0 deg), extracted by
 * marching triangles over the nodal vector potential, stitched, and simplified.
 * Baked rather than fetched so the reveal is instant and needs no solver
 * round-trip — the lesson still runs the real solver a moment later, in Solve.
 *
 * Levels are evenly spaced in Az, so line spacing reads as field strength.
 * Contours within 3 mm of the outer air boundary are dropped: they are
 * shaped by the domain wall rather than the magnet.
 *
 * Provenance: Magneto2D solve, 5210 nodes / 10158 triangles, mesh_source=gmsh.
 * Regenerate with scripts/bake_lesson_one_field.py.
 *
 * Coordinates are millimetres in solver space: +x right, +y UP. SVG y grows
 * downward, so a renderer must negate y — including the arrow directions.
 */

