import assert from 'node:assert/strict';
import { importTypeScriptModule } from './import-typescript-module.mjs';
const { parseCustomSteels, projectMaterialCatalog } = await importTypeScriptModule(new URL('../src/public/customSteel.ts', import.meta.url));
const { parseDesignFile, serializeDesignFile } = await importTypeScriptModule(new URL('../src/public/designFile.ts', import.meta.url));
const { cloneDefaultConfig } = await importTypeScriptModule(new URL('../src/public/model.ts', import.meta.url));
const id = `custom:${'a'.repeat(64)}`;
const material = { id, name: 'Supplier example', source: 'Test data', lamination_thickness_mm: 0.5, curve_sha256: 'b'.repeat(64), bh_curve: [[0,0],[1,100],[2,10000]] };
const config = cloneDefaultConfig();
config.materials.stator_steel = id;
config.materials.custom_steels = { [id]: material };
const reopened = parseDesignFile(serializeDesignFile(config, 'Custom steel project')).config;
assert.deepEqual(reopened.materials, config.materials, 'Saving and reopening must preserve the data and assignment');
const catalog = projectMaterialCatalog({ steels: ['M350-50A', 'M19', 'M27'], magnet_grades: [], conductors: [] }, reopened);
assert.deepEqual(catalog.steels, ['M350-50A', id], 'Unsupported catalog choices must not enter the public selector');
assert.equal(catalog.models[id].capabilities.core_loss, false);
assert.deepEqual(catalog.models[id].curve.points, [[0,0],[100,1],[10000,2]], 'The chart uses H on the horizontal axis');
const broken = structuredClone(material);
broken.bh_curve[2][1] = 50;
assert.throws(() => parseCustomSteels({ [id]: broken }), /must increase/);
const missing = structuredClone(config);
missing.materials.custom_steels = {};
assert.throws(() => parseDesignFile(serializeDesignFile(missing, 'Missing curve')), /missing its custom steel curve/);
assert.throws(() => parseCustomSteels({ 'M350-50A': material }), /Invalid embedded/);
console.log('Custom steel project roundtrip, catalog isolation and malformed-data tests passed');
