import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const base = process.env.COILEM_OUTRUNNER_REVIEW_URL || 'http://127.0.0.1:58152';
const output = new URL('../../output/femm-outrunner-review/operating-modes-browser/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chromium', headless: true });
const page = await browser.newPage({ viewport: { width: 1660, height: 1120 }, acceptDownloads: true });
const errors = [], receipt = {};
page.on('pageerror', error => errors.push(error.stack || error.message));
const shot = name => page.screenshot({ path: fileURLToPath(new URL(name+'.png', output)), fullPage: true });
const open = async benchmark => {
  await page.getByRole('button', { name: 'Design file menu' }).click();
  await page.getByRole('menuitem', { name: 'Examples', exact: true }).hover();
  await page.getByRole('menuitem', { name: benchmark ? /LRK fixed-current benchmark/ : /LRK outrunner 14p/ }).click();
  await page.getByRole('region', { name: 'Outrunner motor viewport' }).waitFor();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(button => button.textContent === 'Continue to Solve')?.disabled);
};
try {
  await page.goto(base); await open(false);
  await page.getByRole('button', { name: 'Show 3D motor view', exact: true }).click();
  await page.getByRole('group', { name: 'Show or hide motor parts' }).waitFor();
  await shot('3d-assembled');
  await page.getByRole('button', { name: 'Exploded', exact: true }).click();
  await page.getByLabel('Exploded view amount', { exact: true }).fill('63');
  assert.equal(await page.getByLabel('Exploded view amount').inputValue(), '63');
  await shot('3d-exploded');
  await page.getByRole('group', { name: 'Show or hide motor parts' }).getByRole('button', { name: 'Magnets', exact: true }).click();
  await page.getByRole('group', { name: 'Show or hide motor parts' }).getByRole('button', { name: 'Magnets', exact: true }).click();
  await page.getByRole('button', { name: 'Exploded', exact: true }).click();
  assert.equal(await page.getByLabel('Exploded view amount').inputValue(), '0');
  receipt.exploded_view_toggle_slider_and_visibility = true;
  await page.getByRole('button', { name: 'Show 2D motor view', exact: true }).click();
  await page.getByRole('button', { name: 'Phases', exact: true }).click();
  await shot('six-step-design');
  await page.getByRole('button', { name: 'Continue to Solve', exact: true }).click();
  const six = page.getByRole('radio', { name: /^Ideal six-step/ });
  assert.equal(await six.getAttribute('aria-checked'), 'true');
  await page.getByRole('button', { name: 'Design file menu' }).click();
  const downloading = page.waitForEvent('download');
  await page.getByRole('menuitem', { name: 'Save design file (.coilem)', exact: true }).click();
  const download = await downloading, savedPath = fileURLToPath(new URL('six-step.coilem', output));
  await download.saveAs(savedPath);
  const saved = JSON.parse(await readFile(savedPath, 'utf8'));
  assert.equal(saved.analysis.excitation_mode, 'ideal_six_step_120');
  assert.equal(saved.analysis.current_amplitude_convention, 'plateau');
  await page.locator('input[type=file][accept*=".coilem"]').setInputFiles(savedPath);
  assert.equal(await six.getAttribute('aria-checked'), 'true');
  await shot('six-step-operating');
  await page.getByRole('button', { name: /^Accuracy plan/ }).click();
  await page.locator('.public-solve-plan-choices button').filter({ hasText: 'Preview' }).click();
  await page.getByRole('button', { name: /^Analysis/ }).first().click();
  await page.getByRole('radio', { name: 'Single operating point (0°)', exact: true }).check();
  await page.getByRole('button', { name: '▶ Run analysis', exact: true }).click();
  await page.getByRole('heading', { name: 'Operating point', exact: true }).waitFor({ timeout: 120000 });
  const sixResult = await page.getByRole('heading', { name: 'Operating point', exact: true }).locator('..').textContent();
  assert.match(sixResult, /55\.3639/); assert.match(sixResult, /CW positive/);
  receipt.six_step_source_torque_CW_mNm = 55.3639;
  await page.getByRole('button', { name: '← Back to Solve', exact: true }).click();
  await page.getByRole('radio', { name: /^Sinusoidal/ }).click();
  await page.getByLabel('Current convention', { exact: true }).selectOption('peak');
  await shot('sinusoidal-operating');
  await page.getByRole('button', { name: '▶ Run analysis', exact: true }).click();
  await page.getByRole('heading', { name: 'Operating point', exact: true }).waitFor({ timeout: 120000 });
  const sineResult = await page.getByRole('heading', { name: 'Operating point', exact: true }).locator('..').textContent();
  assert.match(sineResult, /47\.9634/); assert.match(sineResult, /CW positive/);
  receipt.sinusoidal_source_torque_CW_mNm = 47.9634;
  receipt.saved_mode_roundtrip = true;
  await page.reload(); await open(true);
  await page.getByRole('button', { name: 'Continue to Solve', exact: true }).click();
  assert.equal(await page.getByRole('radio', { name: /^Fixed-current benchmark/ }).getAttribute('aria-checked'), 'true');
  await page.getByRole('button', { name: 'Show Geometry view', exact: true }).click();
  await page.getByRole('button', { name: 'Phases', exact: true }).click();
  await shot('benchmark-fixed-preserved');
  receipt.benchmark_stays_fixed = true;
  assert.deepEqual(errors, []);
  await writeFile(new URL('receipt.json', output), JSON.stringify({ status: 'PASS', default: 'ideal_six_step_120', ...receipt, page_errors: errors }, null, 2));
  console.log('PASS: six-step default, all operating choices, saved mode roundtrip, fresh six-step/sine solves, benchmark preservation and exploded 3D');
} catch (failure) { await shot('failure').catch(() => undefined); console.log('Page errors:', errors); throw failure; }
finally { await browser.close(); }
