"""Recover omitted historical CSVs at their pinned export source, with zero solves.

Copies the archived bundle into a new output directory, regenerates only its
three CSVs using the original checkout, and requires the original file hashes.
Never rewrites the archive or its export-check.json. Requires Python and Node.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path


def regenerate(source: Path, evidence: Path, output: Path) -> None:
    source, evidence, output = source.resolve(), evidence.resolve(), output.resolve()
    if output == evidence or evidence in output.parents:
        raise ValueError('Output must be outside the historical evidence directory')
    receipt = json.loads((evidence / 'export-check.json').read_text())
    environment = json.loads((evidence / 'recheck-environment.json').read_text())
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=source, text=True).strip()
    dirty = subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=no'], cwd=source, text=True).strip()
    if head != environment['source_commit'] or dirty:
        raise ValueError('Source checkout must be clean and match the archived recheck-environment source_commit exactly')
    output.mkdir(parents=True)  # Refuse any existing output, including prior failed attempts.
    for path in evidence.iterdir():
        if path.is_file():
            shutil.copyfile(path, output / path.name)
    runner = "import runpy,sys;path=sys.argv.pop(1);runpy.run_path(path,run_name='__main__')"
    subprocess.run([sys.executable, '-c', runner, str(Path(__file__).resolve()), '--worker', str(output)], cwd=source,
                   env={**os.environ, 'COILEM_BUILD_COMMIT': head}, check=True)
    for name in ('performance.csv', 'idiq.csv', 'map.csv'):
        content = (output / name).read_bytes()
        record = {'bytes': len(content), 'sha256': hashlib.sha256(content).hexdigest()}
        if record != receipt['files'][name]:
            raise ValueError(f'{name}: regenerated bytes differ from the original receipt; output retained for diagnosis')
    print(f'{output}: all three CSVs match the original receipt; zero native solves')


def worker(output: Path) -> None:
    # Run with the PINNED checkout as cwd/sys.path[0]. Rebuild derived report
    # tables with its original writer; this performs no native field solves.
    from backend.models.performance import DriveLimits, FluxLinkageMap
    from backend.performance_report import ReportContext, build_idiq_table_csv, build_performance_csv, performance_data
    analysis = json.loads((output / 'analysis.json').read_text())
    request = json.loads((output / 'request.json').read_text())
    winding = analysis['winding_resistance']
    context = ReportContext(
        design_name=request['project_name'],
        current_unit='A rms' if request['config']['solve_params']['current_amplitude_convention'] == 'rms' else 'A peak',
        dc_bus_source='entered', map_preset=analysis['settings']['preset'],
        phase_resistance={'status': winding['status'], 'reason': winding['status_reason']},
    )
    data = performance_data(
        FluxLinkageMap.model_validate(analysis['map']), DriveLimits.model_validate(analysis['settings']['limits']),
        phase_resistance_ohm=analysis['envelope']['phase_resistance_ohm'],
        winding_temperature_C=analysis['envelope']['winding_temperature_C'], mechanical_loss_W=analysis['mechanical_loss_W'],
        control=analysis['settings']['control'],
    )
    (output / 'performance.csv').write_bytes(build_performance_csv(data, context))
    (output / 'idiq.csv').write_bytes(build_idiq_table_csv(data, context))
    # Match JavaScript String(number) and csvCell exactly, including negative
    # zero/exponent formatting, using the original frontend's mapCsv exporter.
    frontend = Path.cwd() / 'frontend'
    script = """
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const helper = pathToFileURL(process.cwd() + '/scripts/import-typescript-module.mjs');
const { importTypeScriptModule } = await import(helper);
const { mapCsv } = await importTypeScriptModule(pathToFileURL(process.cwd() + '/src/public/performanceView.ts'));
const output = process.argv[1];
const analysis = JSON.parse(fs.readFileSync(output + '/analysis.json', 'utf8'));
fs.writeFileSync(output + '/map.csv', mapCsv(analysis.map));
"""
    subprocess.run(['node', '--input-type=module', '-e', script, str(output)], cwd=frontend, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path)
    parser.add_argument('--evidence', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--worker', type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker:
        worker(args.worker)
    elif args.source and args.evidence and args.output:
        regenerate(args.source, args.evidence, args.output)
    else:
        parser.error('--source, --evidence and --output are required')


if __name__ == '__main__':
    main()
