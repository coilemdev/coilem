"""Run benchmark Phase G (losses) and grade it.

Solves the 16 registered operating points for stator iron and copper loss and
the 8 rotor histories of 384 positions each, grades them, and writes the result
record and a results page. It needs the Magneto2D solver and takes about an
hour on a laptop; FEMM is not needed, because its records are stored.

    python -m tools.run_phase_g --work ~/coilem-phase-g-work     # solve, then write results/coilem.json and RESULTS.md
    python -m tools.run_phase_g --work DIR --only outer_spm      # one motor only (nothing is written to the repository)
    python -m tools.run_phase_g --check                          # fail if the stored files do not agree with each other

Finished points are kept in the work folder, so a stopped run continues where
it was. The folder records the build that solved them (``candidate.json``), and
a run from another build refuses it; ``--discard-work`` deletes its points and
solves them again. One run at a time holds a work folder: a second run started
on it is refused at once. ``--check`` solves nothing: it re-grades the stored
record against the registered references and rebuilds the page from it.
``--regrade`` and a full run store the record and its page only when the record
holds every registered value, and write both or neither.

The stored record, its page and the FEMM references are kept in the private
repository. In a checkout without the record, ``--check`` says so and exits 0;
``--regrade`` exits 1.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import tempfile
from contextlib import ExitStack
from pathlib import Path

from backend.benchmark_suite.loss_phase_g import (
    COPPER_KEYS,
    PROTOCOL,
    RESULTS,
    ROTOR_KEYS,
    STATOR_KEYS,
    WorkFolderError,
    compare,
    run,
    spec,
    spec_sha256,
    work_lock,
)

ROOT = Path(__file__).resolve().parents[1]
PAGE = f"{PROTOCOL}/RESULTS.md"
LOAD_LABELS = {"no_load": "no load", "loaded": "loaded"}


def _rounded(value):
    if isinstance(value, bool) or value is None:
        return value
    if isinstance(value, float):
        return float(f"{value:.9g}")
    if isinstance(value, dict):
        return {key: _rounded(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_rounded(item) for item in value]
    return value


def _watts(value: float) -> str:
    if abs(value) >= 1:
        return f"{value:.3f}"
    return f"{value * 1000:.2f} m" if abs(value) >= 1e-4 else f"{value * 1000:.4f} m"


def _pct(value) -> str:
    return "n/a" if value is None else f"{value:+.2f}%"


def _loss(values: dict | None, key: str) -> str:
    return "missing" if values is None else _watts(values[key])


def page(result: dict) -> str:
    """The results page. Generated, so its numbers cannot drift from the record."""

    registered = spec()
    motors = {row["id"]: row["description"] for row in registered["motors"]}
    cases = {row["id"]: row for row in registered["cases"]}
    graded = result["comparisons"]
    stator, rotor = graded["stator_copper_vs_femm"], graded["rotor_own_checks"]
    versus = graded.get("rotor_vs_femm", {"PASS": 0, "FAIL": 0, "NOT_RUN": len(graded["cases"])})
    lines = [
        "# Phase G results: losses",
        "",
        f"Protocol {registered['protocol_version']}. coilEM {result['coilem_version']} on {result['platform']}. "
        "Generated by `python -m tools.run_phase_g`; do not edit.",
        "",
        "| Check | Pass | Fail | Not run |",
        "|---|---|---|---|",
        f"| Stator iron loss, copper loss and phase resistance against FEMM | {stator['PASS']} | {stator['FAIL']} | {stator['NOT_RUN']} |",
        f"| Rotor iron loss, own checks (closed turn, position doubling) | {rotor['PASS']} | {rotor['FAIL']} | {rotor['NOT_RUN']} |",
        f"| Rotor iron loss against FEMM | {versus['PASS']} | {versus['FAIL']} | {versus['NOT_RUN']} |",
        "",
        f"{graded['rotor_reference']}",
        "",
        "## Stator iron loss and copper loss against FEMM",
        "",
        "Limits: iron loss within 10% of FEMM or 1 mW; copper loss and phase resistance within 1%.",
        "",
        "| Motor | Load | rpm | Stator iron W: coilEM | FEMM | Difference | Hysteresis | Lamination eddy "
        "| Copper W: coilEM | FEMM | Resistance | Result |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in graded["cases"]:
        case = cases[row["id"]]
        if row["stator"] is None:
            continue
        values = row["stator"]["values"]
        iron, copper = values["iron_loss_W"], values["copper_loss_W"]
        lines.append(
            f"| {motors[case['motor']]} | {LOAD_LABELS[case['load']]} | {case['speed_rpm']} | {iron['coilem']:.3f} | {iron['femm']:.3f} | "
            f"{_pct(iron['difference_pct'])} | {_pct(values['iron_hysteresis_loss_W']['difference_pct'])} | "
            f"{_pct(values['iron_eddy_loss_W']['difference_pct'])} | {copper['coilem']:.3f} | {copper['femm']:.3f} | "
            f"{_pct(values['phase_resistance_ohm']['difference_pct'])} | {row['stator']['status']} |")
    lines += [
        "",
        "## Rotor iron loss",
        "",
        "Each motor and load is solved once over a full turn of 384 rotor positions. The loss is then worked out from "
        "every fourth position (96), every second (192) and all of them (384), at both speeds. Limits: the first and "
        "last position of the turn agree to 1e-6 T, and each doubling changes hysteresis, lamination eddy and their "
        "sum by under 5% or 1 mW.",
        "",
        "| Motor | Load | rpm | Rotor iron W: 96 | 192 | 384 | Change 192 to 384 | Hysteresis W | Lamination eddy W | Turn closes to | Result |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    histories = {row["id"]: row for row in result["rotor_histories"]}
    missing = []
    for row in graded["cases"]:
        case = cases[row["id"]]
        history = histories.get(case["rotor_history"])
        if row["rotor"] is None or history is None:
            continue
        # A history without a registered position count is graded FAIL; its page says which count is missing.
        by_count = history["speeds"].get(str(case["speed_rpm"]), {})
        coarse, half, finest = (by_count.get(count) for count in ("96", "192", "384"))
        change = (100 * (finest["total_W"] - half["total_W"]) / finest["total_W"]
                  if finest and half and finest["total_W"] else None)
        if row["rotor"].get("missing_positions"):
            missing.append(f"{motors[case['motor']]}, {LOAD_LABELS[case['load']]}, {case['speed_rpm']} rpm: "
                           f"{', '.join(str(count) for count in row['rotor']['missing_positions'])}")
        lines.append(
            f"| {motors[case['motor']]} | {LOAD_LABELS[case['load']]} | {case['speed_rpm']} | {_loss(coarse, 'total_W')} | "
            f"{_loss(half, 'total_W')} | {_loss(finest, 'total_W')} | {_pct(change)} | {_loss(finest, 'hysteresis_W')} | "
            f"{_loss(finest, 'lamination_eddy_W')} | {history['closure']['max_T']:.1e} T | {row['rotor']['status']} |")
    if missing:
        lines += ["", "Position counts missing from the record, so those rows fail: " + "; ".join(missing) + "."]
    against = [row for row in graded["cases"] if row["rotor"] and row["rotor"].get("reference")]
    if against:
        lines += [
            "",
            "## Rotor iron loss against FEMM",
            "",
            "coilEM's 384-position loss against FEMM's, from the same 384 positions on one fixed FEMM mesh "
            "(tools/phase_g_femm). Limits: each component within 10% of FEMM or 1 mW.",
            "",
            "| Motor | Load | rpm | Solver | Rotor iron W: coilEM | FEMM | Difference | Hysteresis | Lamination eddy | Result |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for row in against:
            case, graded_reference = cases[row["id"]], row["rotor"]["reference"]
            values = graded_reference["values"]
            if values is None:
                # No 384-position result to compare, which fails.
                lines.append(
                    f"| {motors[case['motor']]} | {LOAD_LABELS[case['load']]} | {case['speed_rpm']} | {graded_reference['solver']} | "
                    f"missing | n/a | n/a | n/a | n/a | {graded_reference['status']} |")
                continue
            lines.append(
                f"| {motors[case['motor']]} | {LOAD_LABELS[case['load']]} | {case['speed_rpm']} | {graded_reference['solver']} | "
                f"{_watts(values['total_W']['coilem'])} | {_watts(values['total_W']['femm'])} | {_pct(values['total_W']['difference_pct'])} | "
                f"{_pct(values['hysteresis_W']['difference_pct'])} | {_pct(values['lamination_eddy_W']['difference_pct'])} | "
                f"{graded_reference['status']} |")
    lines += [
        "",
        "## What these numbers do and do not show",
        "",
        "- The stator iron loss and copper loss of this build agree with FEMM within the limits above where the result is PASS. "
        "Both tools use the same steel loss coefficients, so this checks the fields and the arithmetic, not the coefficients.",
        _rotor_reference_note(len(against), versus),
        "- For the outer-rotor motor the rotor ring is treated as laminated M350-50A. A solid steel shell carries larger "
        "eddy currents, which are not calculated.",
        "- Not included anywhere: " + "; ".join(registered["not_included"]) + ".",
        "",
    ]
    return "\n".join(lines)


def _rotor_reference_note(compared: int, versus: dict) -> str:
    settled = ("a PASS on its own checks means the calculation is settled with respect to the number of rotor positions "
               "and that the turn closes, not that the value has been confirmed.")
    if not compared:
        return "- Rotor iron loss has no second solver behind it here. " + settled[0].upper() + settled[1:]
    note = "- Rotor iron loss is compared with FEMM using the same loss coefficients"
    if versus["NOT_RUN"]:
        note += " where a FEMM record is stored. Elsewhere " + settled
    else:
        note += " for every motor and load, so this checks the rotor fields and the arithmetic, not the coefficients."
    if versus["FAIL"]:
        note += (" Where the result against FEMM is FAIL, the two solvers differ by more than the limit and that rotor "
                 "value is not confirmed.")
    return note


def record(result: dict) -> dict:
    result = _rounded(result | {"platform": f"{platform.system()} {platform.machine()}"})
    return result | {"comparisons": _rounded(compare(result))}


def problems_in(stored: dict) -> list[str]:
    """Why a record cannot be stored as the Phase G result: it is for another specification, or it lacks a registered
    case, rotor history, speed, position count or value. An empty list when it is complete."""
    problems = []
    registered = spec()
    if stored.get("spec_sha256") != spec_sha256() or stored.get("protocol_version") != registered["protocol_version"]:
        problems.append("the stored record is for another specification")
    if {row["id"] for row in stored.get("cases", [])} != {row["id"] for row in registered["cases"]}:
        problems.append("the stored record does not hold every registered case")
    if {row["id"] for row in stored.get("rotor_histories", [])} != {row["id"] for row in registered["rotor_histories"]}:
        problems.append("the stored record does not hold every registered rotor history")
    for row in stored.get("cases", []):
        if set(row.get("stator") or {}) != set((*STATOR_KEYS, *COPPER_KEYS)):
            problems.append(f"{row['id']} does not hold the five graded values")
    speeds = {str(speed) for speed in registered["rotor"]["evaluation_speeds_rpm"]}
    counts = {str(count) for count in registered["rotor"]["position_counts"]}
    for row in stored.get("rotor_histories", []):
        by_speed = row.get("speeds") or {}
        if set(by_speed) != speeds or any(set(speed) != counts for speed in by_speed.values()):
            problems.append(f"{row['id']} does not hold every registered speed and position count")
        if any(set(values) != set(ROTOR_KEYS) for speed in by_speed.values() for values in speed.values()):
            problems.append(f"{row['id']} does not hold the three rotor loss components")
    return problems


def check(stored: dict | None = None) -> list[str]:
    """Problems with the stored record (or ``stored``) and the page; an empty list when they agree."""
    stored = stored if stored is not None else json.loads((ROOT / RESULTS).read_text(encoding="utf-8"))
    problems = problems_in(stored)
    if not problems and _rounded(compare(stored)) != stored.get("comparisons"):
        problems.append("the stored grades are not what the stored values and the registered references give")
    if not problems and (ROOT / PAGE).read_text(encoding="utf-8") != page(stored):
        problems.append(f"{PAGE} is not the page of the stored record")
    return problems


def write_outputs(result: dict) -> None:
    """Write the record and its page, or neither.

    Render both files first, then hold the output lock while staging and installing them. If the report cannot
    be replaced, restore the previous record or remove the newly created one. Use LF on every platform.
    """
    record, report = ROOT / RESULTS, ROOT / PAGE
    texts = {record: json.dumps(result, indent=1) + "\n", report: page(result)}
    temporaries = {}
    with work_lock(record.parent), ExitStack() as cleanup:
        for path, text in texts.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            temporaries[path] = path.with_name(f".{path.name}.{os.getpid()}.tmp")
            cleanup.callback(temporaries[path].unlink, missing_ok=True)
            with temporaries[path].open("w", encoding="utf-8", newline="") as stream:
                stream.write(text)
                stream.flush()
                os.fsync(stream.fileno())

        # Keep the exact old record until the report replacement succeeds.
        with ExitStack() as backup_cleanup:
            backup = None
            if record.exists():
                with tempfile.NamedTemporaryFile(dir=record.parent, prefix=f".{record.name}.",
                                                 suffix=".bak", delete=False) as stream:
                    backup = Path(stream.name)
                    backup_cleanup.callback(backup.unlink, missing_ok=True)
                shutil.copy2(record, backup)
            os.replace(temporaries[record], record)
            try:
                os.replace(temporaries[report], report)
            except OSError:
                if backup is None:
                    record.unlink()
                else:
                    # If even restoration fails, keep the backup named in the exception.
                    backup_cleanup.pop_all()
                    os.replace(backup, record)
                raise


def _refuse(problems: list[str], what: str) -> int:
    for problem in problems:
        print(f"Phase G: {problem}")
    print(f"Phase G: {what}; {RESULTS} and {PAGE} were left as they are")
    return 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--work", type=Path, help="Folder outside the repository that keeps finished points")
    parser.add_argument("--discard-work", action="store_true",
                        help="Delete the points kept in --work (for example ones another build solved) and solve them again")
    parser.add_argument("--only", choices=[row["id"] for row in spec()["motors"]], help="Solve one motor and print its grades")
    parser.add_argument("--skip-rotor", action="store_true", help="Leave out the rotor histories (with --only)")
    parser.add_argument("--workers", type=int, default=4, help="Solver processes for a rotor history (default 4)")
    parser.add_argument("--check", action="store_true", help="Verify the stored record and page without solving")
    parser.add_argument("--regrade", action="store_true",
                        help="Grade the stored record again (for example after new FEMM references) and rewrite it and the page, without solving")
    args = parser.parse_args(argv)
    if (args.check or args.regrade) and not (ROOT / RESULTS).is_file():
        print(f"Phase G: the stored record ({RESULTS}) is kept in the private repository and is not in this checkout, "
              f"so there is nothing to {'check' if args.check else 'regrade'}.")
        return 0 if args.check else 1
    if args.check:
        problems = check()
        for problem in problems:
            print(f"Phase G: {problem}")
        print("Phase G stored record and page agree" if not problems else "Phase G check failed")
        return 1 if problems else 0
    if args.regrade:
        stored = json.loads((ROOT / RESULTS).read_text(encoding="utf-8"))
        problems = problems_in(stored)
        if problems:
            return _refuse(problems, "the stored record is incomplete, so it was not regraded")
        stored["comparisons"] = _rounded(compare(stored))
        write_outputs(stored)
        graded = stored["comparisons"]
        print(json.dumps({key: graded[key] for key in ("stator_copper_vs_femm", "rotor_own_checks", "rotor_vs_femm")}))
        print(f"regraded {RESULTS} and {PAGE}")
        return 0
    if args.work is None:
        parser.error("--work is needed to solve")
    if args.skip_rotor and not args.only:
        parser.error("--skip-rotor is for a partial run with --only; the stored record holds every rotor history")
    try:
        solved = run(only=args.only, rotor=not args.skip_rotor, workers=args.workers, work=args.work.expanduser(),
                     discard=args.discard_work)
    except WorkFolderError as error:
        print(f"Phase G: {error}")
        return 1
    if not args.only:
        problems = problems_in(solved)
        if problems:
            return _refuse(problems, f"the run's record is incomplete, so it was not stored (its points stay in {args.work})")
    result = record(solved)
    graded = result["comparisons"]
    print(json.dumps({"stator_copper_vs_femm": graded["stator_copper_vs_femm"], "rotor_own_checks": graded["rotor_own_checks"]}))
    if args.only:
        print(page(result))
        return 0
    write_outputs(result)
    print(f"wrote {RESULTS} and {PAGE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
