"""Run benchmark Phase H (thermal) and grade it against the references on disk.

Solves the 42 registered problems with this build, grades each against every
reference bundle under ``benchmarks/h-v1.0/references``, and writes the result
record and a results page. It needs no solver, FEMM or network access and takes
a few seconds.

    python -m tools.run_phase_h                 # write results/coilem.json and RESULTS.md
    python -m tools.run_phase_h --check         # fail if the stored files are not what this build gives
    python -m tools.run_phase_h --export-request spm_8p12s_concentrated__still_air__in_plane --out request.json

``--export-request`` writes one in-plane problem in full, region outlines
included, for solving in another tool.

The stored record, its page and the FEMM 5 references are kept in the private
repository. In a checkout without them, ``--check`` says so and exits 0, and a
run writes coilEM's answers graded against whatever references are on disk.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict
from pathlib import Path

from backend import __version__
from backend.benchmark_suite.thermal_phase_h import PLANAR_MATERIALS, PLANAR_PARTS, PROTOCOL, RESULTS, compare, planar_problem, run, spec
from backend.benchmark_suite.thermal_phase_h import case as registered_case

ROOT = Path(__file__).resolve().parents[1]
PAGE = f"{PROTOCOL}/RESULTS.md"
COOLING_LABELS = {"still_air": "Still air", "forced_air": "Forced air", "liquid_jacket": "Liquid jacket",
                  "prop_wash": "Prop wash", "cooled_mount": "Cooled mount"}
PART_LABELS = {"winding": "Winding", "teeth": "Teeth", "yoke": "Yoke", "magnets": "Magnets", "rotor": "Rotor"}


def _rounded(value):
    if isinstance(value, bool) or value is None:
        return value
    if isinstance(value, float):
        return round(value, 4)
    if isinstance(value, dict):
        return {key: _rounded(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_rounded(item) for item in value]
    return value


def record() -> dict:
    result = run()
    return _rounded(result | {"comparisons": compare(result)})


def _design_names() -> dict[str, str]:
    return {row["id"]: row["description"] for row in spec()["designs"]}


def page(result: dict) -> str:
    """The results page. Generated, so its numbers cannot drift from the record."""

    names = _design_names()
    cases = {row["id"]: row for row in result["cases"]}
    lines = [
        "# Phase H results", "",
        f"Protocol {result['protocol_version']}, specification `{result['spec_sha256'][:12]}`. Generated by "
        "`python -m tools.run_phase_h`; do not edit by hand. What the cases are and how they are graded is in "
        "[README.md](README.md).", "",
        f"{len(cases)} cases solved. Temperatures are in C with the surroundings at {result['surroundings_C']:g} C.", "",
    ]
    for tool, graded in result["comparisons"].items():
        compared = [row for row in graded["cases"] if row["status"] != "NOT_COMPARED"]
        if not compared:
            continue
        counts = graded["counts"]
        differences = [abs(part["difference_K"]) for row in compared for part in row["parts"]]
        worst = max(((part, row) for row in compared for part in row["parts"]), key=lambda item: abs(item[0]["difference_K"]))
        lines += [
            f"## coilEM against {compared[0]['tool']}", "",
            f"{len(compared)} cases compared: "
            + ", ".join(f"{counts[status]} {status}" for status in ("PASS", "YELLOW", "FAIL") if counts.get(status))
            + f". {counts.get('NOT_COMPARED', 0)} cases have no reference from this tool.",
            f"Largest difference: {worst[0]['difference_K']:+.1f} K on the {worst[0]['part']} of `{worst[1]['case_id']}`. "
            f"Median difference: {sorted(differences)[len(differences) // 2]:.2f} K.", "",
            "Each cell is coilEM / reference, then coilEM minus reference in K.", "",
            "| Design | Cooling | Heat | " + " | ".join(PART_LABELS[part] for part in PLANAR_PARTS) + " | Heat by the mount | Status |",
            "|---|---|---|" + "---|" * len(PLANAR_PARTS) + "---|---|",
        ]
        for row in compared:
            solved = cases[row["case_id"]]
            parts = {part["part"]: part for part in row["parts"]}
            cells = [f"{parts[part]['coilem_C']:.1f} / {parts[part]['reference_C']:.1f} ({parts[part]['difference_K']:+.1f})"
                     if part in parts else "n/a" for part in PLANAR_PARTS]
            mount = next((leaving for leaving in row["exits"] if leaving["exit"] == "mount"), None)
            share = f"{mount['coilem_share_pct']:.1f}% / {mount['reference_share_pct']:.1f}%" if mount else "n/a"
            lines.append(f"| {names[solved['design']]} | {COOLING_LABELS[solved['cooling']]} | {solved['total_heat_W']:.4g} W | "
                         + " | ".join(cells) + f" | {share} | {row['status']} |")
        lines.append("")
    lines += [
        "## coilEM, every case", "",
        "The full-scope cases have no reference yet. The housing column is the mount for an outer rotor.", "",
        "| Design | Cooling | Scope | Heat | Winding | End winding | Teeth | Yoke | Housing or mount | Magnets | Rotor "
        "| Hottest part | Heat leaving by |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for solved in result["cases"]:
        t = solved["temperature_C"]
        exits = ", ".join(f"{name} {100 * watts / solved['total_heat_W']:.0f}%" for name, watts in solved["exit_W"].items())
        lines.append(
            f"| {names[solved['design']]} | {COOLING_LABELS[solved['cooling']]} | {solved['scope'].replace('_', '-')} "
            f"| {solved['total_heat_W']:.4g} W | {t['winding']:.1f} | {t['end_winding']:.1f} | {t['teeth']:.1f} | {t['yoke']:.1f} "
            f"| {t.get('housing', t.get('mount')):.1f} | {t['magnets']:.1f} | {t['rotor']:.1f} "
            f"| {solved['hottest_part'].replace('_', ' ')} | {exits} |")
    return "\n".join(lines) + "\n"


def request(case_id: str) -> dict:
    """One in-plane problem in full, for another tool."""

    row = registered_case(case_id)
    problem = planar_problem(row)
    return {
        "schema": "coilem.thermal_benchmark_request/v1", "case_id": case_id, "protocol_version": spec()["protocol_version"],
        "units": "millimetres; planar depth is the stack length", "depth_mm": problem["depth_mm"], "surroundings_C": spec()["surroundings_C"],
        "heat_W": row["heat_W"], "conductivity_W_mK": problem["conductivity_W_mK"], "source_W_m3": problem["source_W_m3"],
        "cooled_faces": {name: {"radius_mm": face["radius_mm"], "h_W_m2K": face["h_W_m2K"], "surroundings_C": face["surroundings_C"]}
                         for name, face in problem["faces"].items()},
        "other_edges": "insulated", "areas_m2": problem["areas_m2"],
        "regions": [asdict(region) | {"material": PLANAR_MATERIALS[region.kind]} for region in problem["regions"]],
        "report": "Area-weighted mean temperature of " + ", ".join(PLANAR_PARTS) + "; heat leaving each cooled face",
    }


def plain_zeros(value):
    """The value with every -0.0 written as 0.0.

    A balance that rounds to zero can come out as -0.0 on one platform and 0.0 on
    another. They are the same number, but the stored record is compared as
    text, so the record keeps one of them.
    """
    if isinstance(value, float):
        return 0.0 if value == 0 else value
    if isinstance(value, dict):
        return {key: plain_zeros(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [plain_zeros(item) for item in value]
    return value


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare the stored record and page with this build instead of writing them")
    parser.add_argument("--export-request", metavar="CASE", help="write one in-plane problem in full for another tool")
    parser.add_argument("--out", type=Path, help="where --export-request writes")
    args = parser.parse_args()
    if args.export_request:
        if not args.out:
            parser.error("--export-request needs --out")
        args.out.write_text(json.dumps(request(args.export_request), indent=1, allow_nan=False) + "\n", encoding="utf-8")
        return 0
    record_path, page_path = ROOT / RESULTS, ROOT / PAGE
    if args.check and not record_path.is_file() and not page_path.is_file():
        print(f"Phase H: the stored record ({RESULTS}) and page ({PAGE}) are kept in the private repository and are not in "
              "this checkout, so there is nothing to check. Run python -m tools.run_phase_h to write coilEM's answers.")
        return 0
    result = plain_zeros(record() | {"coilem_version": __version__})
    text = json.dumps(result, indent=1, allow_nan=False) + "\n"
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, fresh in ((record_path, text), (page_path, page(result)))
                 if not path.is_file() or path.read_text(encoding="utf-8") != fresh]
        if stale:
            print("Not current: " + ", ".join(stale) + ". Run python -m tools.run_phase_h.")
            return 1
        print("Phase H record and page are current.")
        return 0
    record_path.parent.mkdir(parents=True, exist_ok=True)
    # LF on every platform, as the repository stores them; --check compares text.
    record_path.write_text(text, encoding="utf-8", newline="\n")
    page_path.write_text(page(result), encoding="utf-8", newline="\n")
    print(f"Phase H: {len(result['cases'])} cases solved.")
    for tool, graded in result["comparisons"].items():
        print(f"  against {tool}: " + ", ".join(f"{count} {status}" for status, count in sorted(graded["counts"].items())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
